function autoDescription(name: string, category: string): string {
  const meat = name.match(/с (курицей|говядиной|бараниной|сушёным мясом|домашней колбасой)/i)?.[1];
  if (category === 'Национальная кухня') {
    return meat
      ? `${name} — традиционная домашняя подача с ${meat} и кавказским характером.`
      : `${name} — домашнее блюдо с выразительным кавказским характером.`;
  }
  if (category === 'Вторые блюда') {
    return meat
      ? `${name} — сытная горячая подача с ${meat} и румяным домашним ароматом.`
      : `${name} — сытная горячая подача в уютном домашнем стиле.`;
  }
  if (category === 'Шашлыки') return `${name} — сочная обжарка на углях с ароматом открытого огня.`;
  if (category === 'Мангал') return `${name} — натуральный вкус продуктов, раскрытый жаром мангала.`;
  if (category === 'Рыба') return `${name} — нежная рыбная подача с деликатным ароматом гриля.`;
  if (category === 'Чайная карта') return `${name} — тёплый ароматный чай для спокойной паузы.`;
  if (category === 'Блюда из теста') return `${name} — румяное тесто и домашняя начинка в дагестанском стиле.`;
  if (category === 'Гарниры') return `${name} — простой домашний гарнир, который хорошо дополняет горячие блюда.`;
  return `${name} — домашняя подача с кавказским характером.`;
}

